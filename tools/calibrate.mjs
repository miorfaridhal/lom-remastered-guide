// Fits the tempering simulator's unknowns to the readings in data/calibration.json.
//
// Searches every combination of the model options in js/temper.js, the essence gain k and
// the varnish factor N. Measured readings come first: the fit with the least total error on
// them wins, and guide figures only break ties (then fewer misses, then k nearest 1). Writes
// the result, with every prediction and its error, to data/temper-model.json and CALIBRATION.md.
//
// Usage: node tools/calibrate.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createSimulator, DEFAULT_MODEL } from "../js/temper.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = f => JSON.parse(readFileSync(join(root, f), "utf8"));
const forge = read("data/forge.json"), cal = read("data/calibration.json");
const WEIGHT = { measured: 1000, guide: 1 }; // a point of measured error outweighs any guide error

const options = {
  release: ["none", "cheapest", "even"],
  levels: ["bank", "retro"],
  wizards: ["current", "ever"],
  varnishSlots: ["visible", "all"],
  wizardEnergy: ["none", "group"],
  glowEnergy: ["none", "awake"],
  varnishMode: ["amplify", "scale"],
};
const ks = range(0.8, 1.2, 0.01), Ns = range(1, 12, 0.01);
function range(a, b, step) { const out = []; for (let x = a; x <= b + 1e-9; x += step) out.push(Math.round(x * 100) / 100); return out; }
function* combos(keys, i = 0, acc = {}) {
  if (i === keys.length) { yield { ...acc }; return; }
  for (const v of options[keys[i]]) { acc[keys[i]] = v; yield* combos(keys, i + 1, acc); }
}
const predict = (model, r) => {
  const t = createSimulator(forge, model)(r);
  return t[(r.at || t.length) - 1].power;
};
function score(model) {
  let err = 0, miss = 0;
  for (const r of cal.readings) {
    const d = Math.abs(predict(model, r) - r.power);
    err += WEIGHT[r.kind] * d;
    if (d) miss++;
  }
  return { err, miss };
}

let best = null, tried = 0;
for (const opt of combos(Object.keys(options))) {
  // Essence-free readings do not depend on k or N, and N only matters once varnish triggers,
  // so search k first with a mid N, then N for the best k, then refine k once more.
  let local = null;
  const consider = m => { tried++; const s = score(m); if (!local || better(s, m, local)) local = { ...s, model: m }; };
  for (const k of ks) consider({ ...opt, k, varnishN: 6 });
  for (const varnishN of Ns) consider({ ...opt, k: local.model.k, varnishN });
  for (const k of ks) consider({ ...opt, k, varnishN: local.model.varnishN });
  if (!best || better(local, local.model, best)) best = local;
}
function better(s, m, than) {
  if (s.err !== than.err) return s.err < than.err;
  if (s.miss !== than.miss) return s.miss < than.miss;
  return Math.abs(m.k - 1) < Math.abs(than.model.k - 1);
}

const model = { ...DEFAULT_MODEL, ...best.model };
const sim = createSimulator(forge, model);
const rows = cal.readings.map(r => {
  const t = sim(r), last = t[(r.at || t.length) - 1];
  return { id: r.id, kind: r.kind, material: r.material, type: r.type, actual: r.power, predicted: last.power,
    error: last.power - r.power, levels: last.totalLevels, varnished: last.varnished, source: r.source };
});
const stats = kind => {
  const rs = rows.filter(r => r.kind === kind);
  return { readings: rs.length, exact: rs.filter(r => !r.error).length,
    meanAbsError: +(rs.reduce((a, r) => a + Math.abs(r.error), 0) / rs.length).toFixed(2),
    maxAbsError: Math.max(...rs.map(r => Math.abs(r.error))) };
};
const out = { model, fit: { measured: stats("measured"), guide: stats("guide"), combinationsTried: tried }, readings: rows };
writeFileSync(join(root, "data", "temper-model.json"), JSON.stringify(out, null, 2) + "\n");

const md = [
  "# Tempering simulator calibration",
  "",
  "Generated by `node tools/calibrate.mjs`. Do not edit by hand.",
  "",
  `The simulator (\`js/temper.js\`) was fitted to ${rows.length} readings: ${out.fit.measured.readings} measured in the Android remaster and ${out.fit.guide.readings} printed in fan guides. ${tried.toLocaleString("en")} model combinations were tried.`,
  "",
  "| Fit | Readings | Exact | Mean abs. error | Max abs. error |",
  "|---|---:|---:|---:|---:|",
  `| Measured | ${out.fit.measured.readings} | ${out.fit.measured.exact} | ${out.fit.measured.meanAbsError} | ${out.fit.measured.maxAbsError} |`,
  `| Guide | ${out.fit.guide.readings} | ${out.fit.guide.exact} | ${out.fit.guide.meanAbsError} | ${out.fit.guide.maxAbsError} |`,
  "",
  "## Fitted model",
  "",
  "| Setting | Value | Meaning |",
  "|---|---|---|",
  `| k | ${model.k} | Each essence level adds k × base power ÷ material growth |`,
  `| varnishN | ${model.varnishN} | Varnish multiplies the last attribute item's percentages by this |`,
  `| release | ${model.release} | Where the Nymph of Dawn card's 192 energy goes when it is pushed out |`,
  `| levels | ${model.levels} | bank = levels paid as energy arrives; retro = recomputed from all energy |`,
  `| wizards | ${model.wizards} | Wizard discount counts Sorcerer/Witch cards current on the item, or ever tempered |`,
  `| varnishSlots | ${model.varnishSlots} | The three identical cards may sit in the visible slots only, or in all four |`,
  `| wizardEnergy | ${model.wizardEnergy} | Sulpher / Mercury energy spent on awake elements of their group |`,
  `| glowEnergy | ${model.glowEnergy} | Glow Crystal's own 96 energy spent on awake elements when tempered |`,
  "",
  "## Every reading",
  "",
  "| Reading | Kind | Item | Actual | Predicted | Error | Essence levels |",
  "|---|---|---|---:|---:|---:|---:|",
  ...rows.map(r => `| ${r.id} | ${r.kind} | ${r.material} ${r.type} | ${r.actual} | ${r.predicted} | ${r.error > 0 ? "+" : ""}${r.error} | ${r.levels}${r.varnished ? " (varnished)" : ""} |`),
  "",
  "Readings with no essence and no varnish use only measured rules and must match exactly. The rest depend on the fitted settings, so treat their predictions as estimates.",
  "",
].join("\n");
writeFileSync(join(root, "CALIBRATION.md"), md);

console.log(`Tried ${tried.toLocaleString("en")} combinations.`);
console.log("Model:", JSON.stringify(model));
console.log("Measured:", JSON.stringify(out.fit.measured), "Guide:", JSON.stringify(out.fit.guide));
for (const r of rows) console.log(`${r.id.padEnd(24)} ${r.kind.padEnd(8)} ${String(r.actual).padStart(4)} ${String(r.predicted).padStart(4)} ${r.error > 0 ? "+" : ""}${r.error}`);
